"""Turn pilot JSON into LaTeX macros (results.tex) and the pilot figure (fig_pilot.pdf)."""
import json, numpy as np, matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

R = json.load(open('results/pilot_results.json'))
RING = json.load(open('results/ring_probe.json'))
CUR = json.load(open('results/curves.json'))
OUT = './'
res, ng = R['results'], R['ngram']
order = ['input-only', 'ESN', 'LIF', 'LIF-slow', 'LIF+STDP']
names = {'input-only': 'Input only (no reservoir)', 'ESN': 'Echo state network (null model)', 'LIF': 'LIF spiking reservoir (frozen)',
         'LIF-slow': 'LIF, slow synapses (50 ms)', 'LIF+STDP': 'LIF after STDP exposure'}
ms = lambda v: (float(np.mean(v)), float(np.std(v)))
stats = {k: {m: ms(res[k][m]) for m in ['MC', 'MG_NRMSE', 'char_acc']} for k in order}
best = {'MC': max(order, key=lambda k: stats[k]['MC'][0]), 'MG_NRMSE': min(order, key=lambda k: stats[k]['MG_NRMSE'][0]),
        'char_acc': max(order, key=lambda k: stats[k]['char_acc'][0])}

def cell(k, m, fmt):
    mu, sd = stats[k][m]; s = f'{mu:{fmt}} $\\pm$ {sd:{fmt}}'
    return f'\\textbf{{{s}}}' if best[m] == k else s

rows = ' \\\\\n'.join(f"{names[k]} & {cell(k,'MC','.2f')} & {cell(k,'MG_NRMSE','.3f')} & {cell(k,'char_acc','.3f')}" for k in order) + ' \\\\'
ringrows = ' \\\\\n'.join(f"{k} & {v['mc_k_ge_1']:.2f} & {v['rate_hz']:.1f}" for k, v in RING.items()) + ' \\\\'
mc = {k: stats[k]['MC'][0] for k in order}; mg = {k: stats[k]['MG_NRMSE'][0] for k in order}; ch = {k: stats[k]['char_acc'][0] for k in order}
rates = [r[2] for r in R['LIF_mean_rate_hz'] if r[0] == 'LIF']

rate_of = lambda nm: np.mean([r[2] for r in R['LIF_mean_rate_hz'] if r[0] == nm])
narr = (
    f"The equal-size echo state network was the best substrate on all three tasks, so \\Hy{{0}} is not rejected at this scale. "
    f"On memory capacity the ESN reached {mc['ESN']:.1f}, against {mc['LIF']:.2f} for the frozen LIF reservoir, {mc['LIF-slow']:.2f} with slow synapses and {mc['LIF+STDP']:.2f} after STDP exposure. "
    f"On Mackey--Glass the ESN's error ({mg['ESN']:.3f}) was roughly sixty times lower than the best spiking variant ({mg['LIF-slow']:.3f}, slow synapses). "
    f"The fast-synapse LIF reservoir ({mg['LIF']:.3f}) and its STDP variant ({mg['LIF+STDP']:.3f}) did worse than a readout of the raw input ({mg['input-only']:.3f}), because low-pass spike traces encode the current value only partially. "
    f"Next-character prediction split the spiking variants. The frozen LIF reservoir ({ch['LIF']:.3f}) and its STDP variant ({ch['LIF+STDP']:.3f}) beat the input-only readout ({ch['input-only']:.3f}, which equals the bigram reference), so they carried usable context. "
    f"Both stayed below the ESN ({ch['ESN']:.3f}) and well below a count-based trigram ({ng['trigram']:.3f}). "
    f"Slow synapses, which helped on the two continuous tasks, dropped next-character accuracy to {ch['LIF-slow']:.3f}, just under the input-only readout; their longer integration appears to blur successive symbols. "
    f"STDP exposure raised memory capacity modestly ({mc['LIF']:.2f} to {mc['LIF+STDP']:.2f}) without improving next-character accuracy. "
    f"Mean firing rates were {rate_of('LIF'):.1f}\\,Hz (LIF), {rate_of('LIF+STDP'):.1f}\\,Hz (after STDP) and {rate_of('LIF-slow'):.1f}\\,Hz (slow synapses), so none of the networks was silent or saturated. "
    f"The pattern points to time scale as the binding constraint: the change that most improved spiking memory also showed that the right time scale depends on the task."
)
tex = f"""% auto-generated by make_results.py
\\newcommand{{\\Nseeds}}{{{len(R['seeds'])}}}
\\newcommand{{\\WIN}}{{{R['win_ms']}}}
\\newcommand{{\\MCLIF}}{{{mc['LIF']:.2f}}}
\\newcommand{{\\MCLIFslow}}{{{mc['LIF-slow']:.2f}}}
\\newcommand{{\\MCESN}}{{{mc['ESN']:.1f}}}
\\newcommand{{\\ResultRows}}{{{rows}}}
\\newcommand{{\\NgramRow}}{{{ng['unigram']:.3f} / {ng['bigram']:.3f} / {ng['trigram']:.3f}}}
\\newcommand{{\\RingRows}}{{{ringrows}}}
\\newcommand{{\\PilotNarrative}}{{{narr}}}
"""
open(OUT + 'results.tex', 'w').write(tex)

# figure
plt.rcParams.update({'font.family': 'sans-serif', 'font.size': 9, 'axes.spines.top': False, 'axes.spines.right': False})
fig, ax = plt.subplots(1, 2, figsize=(7.2, 2.7), gridspec_kw={'width_ratios': [1.25, 1]})
col = {'ESN': '#5B6378', 'LIF': '#1FA58C', 'LIF-slow': '#7E4FD1'}
lab = {'ESN': 'ESN (null)', 'LIF': 'LIF', 'LIF-slow': 'LIF, slow synapses'}
for k in ['ESN', 'LIF', 'LIF-slow']:
    v = CUR[k]; ax[0].plot(range(len(v)), v, color=col[k], lw=1.8, label=f"{lab[k]}")
ax[0].set_xlabel('delay $k$ (presentation windows)'); ax[0].set_ylabel('$r^2(k)$'); ax[0].set_ylim(-0.02, 1.02); ax[0].legend(frameon=False)
ax[0].set_title('Linear memory by delay (seed 0)', fontsize=9)
ks = order; mu = [stats[k]['char_acc'][0] for k in ks]; sd = [stats[k]['char_acc'][1] for k in ks]
cc = ['#B9C0CF', '#5B6378', '#1FA58C', '#7E4FD1', '#4CC9B0']
ax[1].bar(range(len(ks)), mu, yerr=sd, color=cc, capsize=2)
for nm, ls in [('bigram', ':'), ('trigram', '--')]:
    ax[1].axhline(ng[nm], color='#D98B12', ls=ls, lw=1.2); ax[1].text(-0.45, ng[nm] + .002, nm, color='#D98B12', fontsize=7, ha='left', va='bottom')
ax[1].set_xticks(range(len(ks))); ax[1].set_xticklabels(['input\nonly', 'ESN', 'LIF', 'LIF\nslow', 'LIF\n+STDP'], fontsize=7.5)
ax[1].set_ylim(0.25, max(max(mu), ng['trigram']) + 0.03); ax[1].set_ylabel('next-char accuracy'); ax[1].set_title('Next-character prediction', fontsize=9)
fig.tight_layout(); fig.savefig(OUT + 'fig_pilot.pdf'); fig.savefig('docs/pilot_results.png', dpi=160)
print(tex)
